"""Downloads the fonts the app uses into public/fonts and writes src/fonts.css, so no page ever calls Google.

Run from anywhere: python projects/ehrms-v2/tools/fetch_fonts.py (needs internet, only when the font list changes).
The generated files are committed (run Prettier on src/fonts.css afterwards); the app itself never reaches out at run time. Only the character sets the app
needs are kept: Latin (+ extended, for accented French names) and Arabic. Licences: Plus Jakarta Sans, Noto Sans Arabic
and IBM Plex Mono are SIL Open Font License 1.1; Material Icons is Apache 2.0 (see public/fonts/LICENSES.txt)."""
import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = ROOT / "public" / "fonts"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"

# family, CSS2 query, subsets to keep
FAMILIES = [
    ("Plus Jakarta Sans", "family=Plus+Jakarta+Sans:wght@400;500;600;700", {"latin", "latin-ext"}),
    ("Noto Sans Arabic", "family=Noto+Sans+Arabic:wght@400;500;600;700", {"arabic"}),
    ("IBM Plex Mono", "family=IBM+Plex+Mono:wght@400;500", {"latin", "latin-ext"}),
]


def get(url, binary=False):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = r.read()
    return data if binary else data.decode("utf-8")


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def blocks(css):
    """(subset comment, properties dict) of every @font-face in a Google Fonts stylesheet."""
    for m in re.finditer(r"/\* ([\w-]+) \*/\s*@font-face\s*\{(.*?)\}", css, re.S):
        props = dict(re.findall(r"([\w-]+):\s*(.*?);", m.group(2), re.S))
        yield m.group(1), props


def download(url, name):
    target = FONTS / name
    if not target.exists():
        target.write_bytes(get(url, binary=True))
    return name


FONTS.mkdir(parents=True, exist_ok=True)
out = ["""/* GENERATED by tools/fetch_fonts.py: the fonts are served from /fonts, never from Google. Do not edit by hand. */
"""]

for family, query, keep in FAMILIES:
    css = get(f"https://fonts.googleapis.com/css2?{query}&display=swap")
    # (subset, file url, unicode-range) -> weights that share the file (variable fonts share one file)
    groups = {}
    for subset, props in blocks(css):
        if subset not in keep:
            continue
        url = re.search(r"url\((.*?)\)", props["src"]).group(1)
        key = (subset, url, props["unicode-range"])
        groups.setdefault(key, []).append(int(props["font-weight"]))
    for (subset, url, unicode_range), weights in groups.items():
        weights.sort()
        name = download(url, f"{slug(family)}-{subset}" + ("" if len(weights) > 1 else f"-{weights[0]}") + ".woff2")
        weight = f"{weights[0]} {weights[-1]}" if len(weights) > 1 else str(weights[0])
        out.append(f"""@font-face {{
  font-family: '{family}';
  font-style: normal;
  font-weight: {weight};
  font-display: swap;
  src: url('/fonts/{name}') format('woff2');
  unicode-range: {unicode_range};
}}
""")

# Material Icons: one file, plus the .material-icons class that Google's stylesheet normally supplies.
icons_css = get("https://fonts.googleapis.com/icon?family=Material+Icons")
icons_url = re.search(r"url\((.*?)\)", icons_css).group(1)
icons = download(icons_url, "material-icons.woff2")
class_rule = re.search(r"\.material-icons\s*\{.*?\}", icons_css, re.S).group(0)
out.append(f"""@font-face {{
  font-family: 'Material Icons';
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url('/fonts/{icons}') format('woff2');
}}

{class_rule}
""")

(ROOT / "src" / "fonts.css").write_text("\n".join(out), encoding="utf-8", newline="\n")
(FONTS / "LICENSES.txt").write_text(
    "Plus Jakarta Sans, Noto Sans Arabic, IBM Plex Mono: SIL Open Font License 1.1 (https://openfontlicense.org).\n"
    "Material Icons: Apache License 2.0 (https://www.apache.org/licenses/LICENSE-2.0).\n"
    "Downloaded from Google Fonts by tools/fetch_fonts.py.\n", encoding="utf-8", newline="\n")
print("ok:", sorted(p.name for p in FONTS.iterdir()))
